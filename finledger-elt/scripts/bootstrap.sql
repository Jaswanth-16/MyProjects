-- Select a Snowflake database/schema before executing.
CREATE TABLE IF NOT EXISTS RAW_TRANSACTIONS (
  transaction_id VARCHAR, account_id VARCHAR, transaction_date DATE,
  amount NUMBER(18,2), currency VARCHAR, status VARCHAR, updated_at TIMESTAMP_NTZ
);
CREATE FILE FORMAT IF NOT EXISTS FINLEDGER_CSV TYPE=CSV SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='"';
CREATE STAGE IF NOT EXISTS FINLEDGER_STAGE FILE_FORMAT=FINLEDGER_CSV;
-- Upload CSV to @FINLEDGER_STAGE using Snowsight or SnowSQL PUT first.
COPY INTO RAW_TRANSACTIONS FROM @FINLEDGER_STAGE FILE_FORMAT=(FORMAT_NAME=FINLEDGER_CSV) ON_ERROR='ABORT_STATEMENT';
